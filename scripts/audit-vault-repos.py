"""Generate a local, read-only, evidence-backed GitHub/vault coordination backlog."""

import argparse
import importlib.util
import json
import re
from datetime import datetime, timezone
from pathlib import Path


spec = importlib.util.spec_from_file_location(
    "vault_sync", Path(__file__).with_name("sync-github-vault.py")
)
sync = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sync)


def markdown(value):
    return str(value).replace("\n", " ").replace("\r", " ").replace("|", "\\|")


def documentation_gaps(files, description, archived=False):
    """Inventory checks are workflow candidates, not claims of broken application code."""
    if archived:
        return []
    gaps = []
    if not description:
        gaps.append(("metadata", "Missing GitHub description", "Repository description is empty."))
    visible = [name for name in files if not any(part.startswith(".") for part in name.split("/"))]
    if not visible:
        gaps.append(("scope", "Define purpose before implementation",
                     "Default branch has no non-hidden files; may be an intentional placeholder."))
        return gaps
    if not any(re.match(r"(^|/)readme(\.[^/]*)?$", name, re.I) for name in files):
        gaps.append(("docs", "Add a project README", "No tracked README filename on the default branch."))
    if not any(re.match(r"\.github/workflows/[^/]+\.ya?ml$", name, re.I) for name in files):
        gaps.append(("ci", "Review whether automated validation is needed",
                     "No tracked GitHub Actions workflow on the default branch; absence is not a failing build."))
    return gaps


def description_for(repo, readme, files):
    if repo.get("description"):
        return repo["description"], "Existing GitHub repository description"
    heading = next(
        (line.lstrip("# ").strip() for line in readme.splitlines()
         if re.match(r"^#{1,2}\s+\S", line)), None
    )
    fenced = False
    paragraphs = []
    paragraph = []
    for line in readme.splitlines():
        stripped = line.strip()
        if stripped.startswith(("```", "~~~")):
            fenced = not fenced
        if fenced or not stripped or stripped.startswith(("#", "|", "!", "[", "<", "-", "*", "```", "~~~")):
            if paragraph:
                paragraphs.append(" ".join(paragraph))
                paragraph = []
            continue
        paragraph.append(stripped)
    if paragraph:
        paragraphs.append(" ".join(paragraph))
    if paragraphs:
        return paragraphs[0][:240], "Draft excerpt from tracked README prose; review before publishing"
    if heading:
        return heading[:240], "Draft from tracked README heading; review before publishing"
    if not any(not name.startswith(".") for name in files):
        return "Purpose needs owner confirmation; default branch is empty or dotfile-only.", "File inventory only"
    return "Purpose needs owner confirmation; no description or README heading found.", "File inventory only"


def relationship_targets(text, names, own_name):
    return [
        name for name in names if name != own_name
        and re.search(r"https://github\.com/" + re.escape(name) + r"(?=$|[/#?\s)>\]\"'])",
                      text, re.I)
    ]


def generated_file(path, text):
    if path.exists() and not path.read_text(encoding="utf-8").startswith("<!-- Generated by audit-vault-repos.py"):
        raise RuntimeError(f"Refusing to overwrite a user-authored note: {path}")
    path.write_text("<!-- Generated by audit-vault-repos.py; put your edits in Decisions.md. -->\n"
                    + text.rstrip() + "\n", encoding="utf-8")


def local_status(root, repo, state, verification):
    if state is not None:
        return state
    mirror = root / "History" / repo["full_name"]
    if not (mirror / "HEAD").is_file():
        return None
    invalid = sync.invalid_tree_paths(mirror, repo["default_branch"]) or []
    verified = next(
        (entry for entry in verification.get("histories", []) if entry["name"] == repo["full_name"]),
        None,
    )
    errors = []
    if repo["full_name"] in verification.get("partial_repositories", []):
        errors.append(
            f"Content-download errors were recorded by full-history verification at "
            f"{verification['verified_at']}; current-cycle result is not yet available. "
            "Consult sync.log for the last observed LFS failure."
        )
    return {
        "name": repo["full_name"],
        "status": "verified-history / current-cycle status unavailable" if verified
                  else "local-history / sync status unavailable",
        "commits": verified["commits"] if verified else None,
        "windows_incompatible_paths": invalid, "errors": errors,
        "source": "Local history plus verification.json, not an invented successful sync result",
    }


def collect(root, repo, state, names):
    mirror = root / "History" / repo["full_name"]
    branch = "refs/heads/" + repo["default_branch"]
    refs = sync.git(mirror, "for-each-ref", "--format=%(refname)", "refs/heads").splitlines()
    files = []
    readme = ""
    readme_path = None
    if branch in refs:
        files = [
            name.decode("utf-8") for name in
            sync.git(mirror, "ls-tree", "-r", "--name-only", "-z", branch, binary=True).split(b"\0")
            if name
        ]
        readme_path = next(
            (name for name in files if re.match(r"^(?:\.github/)?readme\.md$", name, re.I)), None
        )
        if readme_path:
            size = int(sync.git(mirror, "cat-file", "-s", f"{branch}:{readme_path}"))
            if size <= 256 * 1024:
                readme = sync.git(mirror, "show", f"{branch}:{readme_path}")
    description, source = description_for(repo, readme, files)
    gaps = [
        {"category": category, "title": title, "evidence": evidence, "kind": "review"}
        for category, title, evidence in
        documentation_gaps(files, repo.get("description"), repo["archived"])
    ]
    if state is None:
        gaps.append({
            "category": "sync", "title": "Import or finish sync inventory",
            "evidence": "Repository is absent from the local sync status snapshot.",
            "kind": "blocker",
        })
    for error in (state or {}).get("errors", []):
        gaps.append({"category": "sync", "title": "Resolve reported sync error",
                     "evidence": error, "kind": "blocker"})
    invalid = (state or {}).get("windows_incompatible_paths", [])
    if invalid:
        gaps.append({
            "category": "paths", "title": "Review a portable-filenames repair branch",
            "evidence": f"{len(invalid)} default-branch paths cannot be checked out natively on Windows. "
                        "Renaming requires checking references; history mirror and mapped snapshot remain available.",
            "kind": "blocker",
        })
    if ("original sources were not found" in readme.lower()
            and "deployed bundles" in readme.lower()):
        gaps.append({
            "category": "source", "title": "Recover original sources before substantial bundle edits",
            "evidence": "Tracked README states deployed bundles exist but original sources were not found. "
                        "Locate the original source/build pipeline before proposing substantial Worker changes.",
            "kind": "review",
        })
    errors = []
    issues = []
    if repo["has_issues"]:
        try:
            issues = sync.api(
                f"repos/{repo['full_name']}/issues?state=open&per_page=100", pages=True
            )
        except RuntimeError as error:
            errors.append(f"GitHub issue/PR inventory failed: {error}")
    workflow_files = [name for name in files if re.match(r"\.github/workflows/[^/]+\.ya?ml$", name)]
    latest = None
    if workflow_files:
        try:
            runs = sync.api(f"repos/{repo['full_name']}/actions/runs?per_page=1")["workflow_runs"]
            latest = (
                {key: runs[0][key] for key in
                 ("html_url", "status", "conclusion", "head_branch", "head_sha")}
                if runs else None
            )
            if latest and latest["conclusion"] in ("failure", "timed_out", "action_required"):
                gaps.append({
                    "category": "ci", "title": "Investigate latest workflow result",
                    "evidence": f"{latest['conclusion']} on branch {latest['head_branch']}; "
                                f"{latest['html_url']}. Logs have not been diagnosed.",
                    "kind": "blocker",
                })
        except RuntimeError as error:
            errors.append(f"Latest workflow inventory failed: {error}")
    return {
        "name": repo["full_name"], "private": repo["private"], "archived": repo["archived"],
        "fork": repo["fork"], "description": description, "description_source": source,
        "default_branch": repo["default_branch"], "branches": refs, "tracked_files": len(files),
        "readme": readme_path, "workflows": workflow_files,
        "worker_configs": [name for name in files if re.search(r"(^|/)wrangler[^/]*\.(toml|jsonc?)$", name)],
        "related_repos": relationship_targets(readme, names, repo["full_name"]),
        "issues": [
            {"number": issue["number"], "title": issue["title"], "url": issue["html_url"],
             "kind": "pull request" if "pull_request" in issue else "issue"}
            for issue in issues
        ],
        "latest_workflow": latest, "sync": state, "gaps": gaps, "inventory_errors": errors,
    }


def render_note(repo):
    name = repo["name"]
    lines = [
        f"# {name}", "", "[[GitHub Live/Coordinator/00 Repository coordinator|Coordinator]] | "
        "[[GitHub Live/Coordinator/Backlog|Shared backlog]]", "",
        "## Description", "", repo["description"], "",
        f"Source: {repo['description_source']}. This is a local description, not a published metadata change.",
        "", "## Evidence snapshot", "",
        f"- GitHub: https://github.com/{name}",
        f"- Default branch: `{repo['default_branch']}`",
        f"- Visibility: {'Private' if repo['private'] else 'Public'}; archived: {repo['archived']}; fork: {repo['fork']}",
        f"- Local branch refs: {len(repo['branches'])}; tracked files: {repo['tracked_files']}",
        f"- README: `{repo['readme'] or 'not found on the inspected branch'}`",
        f"- GitHub Actions workflow files: {len(repo['workflows'])}",
        f"- Sync status: {(repo['sync'] or {}).get('status', 'not recorded')}",
        f"- Full history: `GitHub Live/History/{name}`",
        f"- Editable working copy (when Windows-compatible): `GitHub Live/Repositories/{name}`",
        f"- Earlier snapshot: `GitHub Imports/{name}`",
        "", "## Missing items and repair candidates", "",
    ]
    for gap in repo["gaps"]:
        lines += [f"- [ ] **{gap['title']}** ({gap['kind']}): {markdown(gap['evidence'])}"]
    if not repo["gaps"]:
        lines.append("No gaps from these limited inventory checks; application correctness has not been tested.")
    lines += ["", "## Existing GitHub work", ""]
    for issue in repo["issues"]:
        lines.append(
            f"- [{name}#{issue['number']}]({issue['url']}) ({issue['kind']}): {markdown(issue['title'])}"
        )
    if not repo["issues"]:
        lines.append("No open items returned (see inventory errors if retrieval failed or issues are disabled).")
    if repo["latest_workflow"]:
        run = repo["latest_workflow"]
        lines += ["", f"Latest observed workflow: [{run['status']} / {run['conclusion']}]({run['html_url']}) "
                  f"on `{run['head_branch']}`. This is not a diagnosis or full CI history."]
    lines += ["", "## Branches available in full history", ""]
    lines += [f"- `{branch.removeprefix('refs/heads/')}`" for branch in repo["branches"]]
    if not repo["branches"]:
        lines.append("No branch refs found; check whether the repository is empty.")
    lines += ["", "## Connected repositories", ""]
    if repo["related_repos"]:
        lines += [
            f"- [[GitHub Live/Coordinator/Repositories/{related.split('/')[-1]}|{related}]] "
            "(explicit GitHub URL in tracked README)"
            for related in repo["related_repos"]
        ]
    else:
        lines.append("No exact owned-repository URL links found in the inspected README.")
    lines += ["", "## Worker / agent connection", ""]
    if repo["worker_configs"]:
        lines += [f"- Existing configuration: `{name}`" for name in repo["worker_configs"]]
        lines.append("Review existing Worker bindings and source before adding a coordinator; no deployment was attempted.")
    else:
        lines.append("No tracked Wrangler configuration found; a Worker is not required for local vault coordination.")
    lines += [
        "", "## Approval and completion", "",
        "1. Confirm the candidate scope and inspect the referenced source or error.",
        "2. Create a repair branch only for a confirmed change; never edit the auto-pushed public default branch.",
        "3. Link a scoped issue/PR to this note only after approval to publish.",
        "4. Run repository-specific tests; record the result and branch/PR in [[GitHub Live/Coordinator/Decisions|Decisions]].",
        "5. Do not mark unavailable files recovered or incomplete features finished without verification.",
    ]
    if repo["inventory_errors"]:
        lines += ["", "## Inventory errors", ""] + [f"- {markdown(error)}" for error in repo["inventory_errors"]]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vault", type=Path, required=True)
    args = parser.parse_args()
    root = sync.ignored_library(args.vault.resolve(strict=True))
    status = json.loads((root / "status.json").read_text(encoding="utf-8"))
    states = {repo["name"]: repo for repo in status["repositories"]}
    completed = root / "last-completed-status.json"
    if completed.exists():
        for repo in json.loads(completed.read_text(encoding="utf-8"))["repositories"]:
            states.setdefault(repo["name"], repo)
    verification_path = root / "verification.json"
    verification = (
        json.loads(verification_path.read_text(encoding="utf-8"))
        if verification_path.exists() else {}
    )
    owner = sync.api("user")["login"]
    repos = [
        repo for repo in sync.api("user/repos?affiliation=owner&per_page=100&sort=full_name", pages=True)
        if repo["owner"]["login"].lower() == owner.lower()
    ]
    names = [repo["full_name"] for repo in repos]
    records = []
    output = root / "Coordinator"
    (output / "Repositories").mkdir(parents=True, exist_ok=True)
    for repo in repos:
        print(f"Auditing {repo['full_name']} (read-only)...", flush=True)
        record = collect(
            root, repo, local_status(root, repo, states.get(repo["full_name"]), verification), names
        )
        records.append(record)
        generated_file(output / "Repositories" / f"{repo['name']}.md", render_note(record))
    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "sync_snapshot_at": status["updated_at"], "owner": owner, "repositories": records,
    }
    sync.save_json(output / "inventory.json", report)
    index = [
        "# Repository coordinator", "",
        "Local connection map for GitHub, the vault, and approval-gated repair work.",
        f"Observed: {report['generated_at']}; sync snapshot: {status['updated_at']}.",
        "Read-only inventory: no repository source edits, branches, issues, pushes, or deployments.",
        "Descriptions from existing metadata or README headings are drafts, not invented feature claims.",
        "", "[[GitHub Live/Coordinator/Backlog|Repair and workflow backlog]] | "
        "[[GitHub Live/Coordinator/Decisions|Decisions and completion records]]",
        "", "| Repository | Description | Candidates | Open GitHub items |",
        "| --- | --- | ---: | ---: |",
    ]
    backlog = [
        "# Repair and workflow backlog", "",
        "[[GitHub Live/Coordinator/00 Repository coordinator|Repository map]]", "",
        "Generated candidates, not confirmed bugs. Sync errors and reported CI failures come first.",
        "README/metadata/CI absences require owner review; empty and archived repositories may be intentional.",
        "No branch has been created: each repair needs a scoped, verified implementation.",
        "Keep manual decisions outside this regenerated note in [[GitHub Live/Coordinator/Decisions|Decisions]].",
        "", "| Kind | Repository | Candidate | Evidence |",
        "| --- | --- | --- | --- |",
    ]
    for repo in records:
        link = f"[[GitHub Live/Coordinator/Repositories/{repo['name'].split('/')[-1]}|{repo['name']}]]"
        index.append(f"| {link} | {markdown(repo['description'])} | {len(repo['gaps'])} | {len(repo['issues'])} |")
    for repo in sorted(records, key=lambda repo: not any(gap["kind"] == "blocker" for gap in repo["gaps"])):
        link = f"[[GitHub Live/Coordinator/Repositories/{repo['name'].split('/')[-1]}|{repo['name']}]]"
        for gap in repo["gaps"]:
            backlog.append(
                f"| {gap['kind']} | {link} | {gap['title']} | {markdown(gap['evidence'])} |"
            )
    index += [
        "", "## Shared workflow", "",
        "- This coordinator stays local. Private notes and recordings are not exposed to cloud Workers.",
        "- GitHub issues/PRs remain the published work queue; this vault links them without duplicating state.",
        "- Repository branches/tags are inventoried from full-history mirrors; default-branch files are inspected only.",
        "- README links establish explicit relationships, not inferred dependencies.",
        "- Existing Wrangler configs identify Worker integration candidates; deployments and new infrastructure need approval.",
        "- A cloud agent cannot access this Windows vault directly. Any future connector needs explicit data boundaries,",
        "  authentication, job approvals, and an outbound local bridge; do not expose the localhost Obsidian API.",
        "- For an approved task: choose one candidate, inspect its source, make a dedicated repair branch, test, then review a PR.",
        "- Regenerate with `python scripts\\audit-vault-repos.py --vault <vault>`; generated notes are replaced,",
        "  but Decisions.md is preserved. This report is not scheduled and makes no model calls.",
    ]
    generated_file(output / "00 Repository coordinator.md", "\n".join(index))
    generated_file(output / "Backlog.md", "\n".join(backlog))
    decisions = output / "Decisions.md"
    if not decisions.exists():
        decisions.write_text(
            "# Decisions and completion records\n\n"
            "[[GitHub Live/Coordinator/00 Repository coordinator|Repository map]]\n\n"
            "Use this non-generated note for approved scope, verified fixes, branches, test results, "
            "and issue/PR links. Nothing is approved or completed merely by appearing in the inventory.\n",
            encoding="utf-8",
        )
    errors = sum(len(repo["inventory_errors"]) for repo in records)
    print(f"Created {len(records)} repository notes, {sum(len(repo['gaps']) for repo in records)} "
          f"review/blocker candidates and {errors} retrieval errors in {output}.")
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
